pub fn find(language: &str) -> Option<&'static Syntax> {
	let name = language.split_whitespace().next()?.to_ascii_lowercase();
	Some(match name.as_str() {
		"rust" | "rs" => &RUST,
		"javascript" | "js" | "jsx" | "mjs" | "cjs" => &JAVASCRIPT,
		"typescript" | "ts" | "tsx" => &TYPESCRIPT,
		"python" | "py" | "python3" => &PYTHON,
		"go" | "golang" => &GO,
		"c" | "h" => &C,
		"cpp" | "c++" | "cc" | "cxx" | "hpp" | "hxx" => &CPP,
		"java" => &JAVA,
		"cs" | "csharp" | "c#" => &CSHARP,
		"json" | "jsonc" | "json5" => &JSON,
		"toml" => &TOML,
		"yaml" | "yml" => &YAML,
		"sh" | "bash" | "shell" | "zsh" => &SHELL,
		"html" | "htm" | "xml" | "svg" => &HTML,
		"css" | "scss" | "less" => &CSS,
		"sql" | "mysql" | "pgsql" | "postgresql" | "sqlite" => &SQL,
		_ => return None,
	})
}
